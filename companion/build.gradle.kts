val ostromCoreVersion = providers.gradleProperty("ostromCoreVersion").get()

// The app's version for the settings screen and the User-Agent, from gradle.properties (release-please keeps it).
val generatedBuildInfo = layout.buildDirectory.dir("generated/build-info/kotlin")
val generateBuildInfo by tasks.registering {
    val version = project.version.toString()
    val output = generatedBuildInfo
    inputs.property("version", version)
    outputs.dir(output)
    doLast {
        val file = output.get().file("run/ostrom/app/BuildInfo.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |// Generated by :companion:generateBuildInfo from gradle.properties; do not edit.
            |package run.ostrom.app
            |
            |internal object BuildInfo {
            |    const val VERSION: String = "$version"
            |}
            |""".trimMargin(),
        )
    }
}

